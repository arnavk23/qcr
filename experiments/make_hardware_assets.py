"""Numbers for the real-hardware paragraph of the paper.

Inputs:  results/hardware/ibm_marrakesh_v1/{plan,analysis}.json (gen_hardware.py run and analyze),
         results/hardware/fake_torino_dry/analysis.json (the noise-model dry run of the same plan).
Outputs: paper/hw_real_numbers.tex.

The metric is the probability of the ideal (deterministic) output. Ratios are geometric means over circuits of the
per-circuit mean over repeats, relative to Qiskit level 3, as in gen_hardware.analyze.
"""

import json
from pathlib import Path

import numpy as np
from common import RESULTS

EXT = Path(__file__).resolve().parents[1] / "manuscripts" / "paper"
H = RESULTS / "hardware"
M = {}


def cmd(name, val):
    M[name] = val


real = json.load(open(H / "ibm_marrakesh_v1" / "analysis.json"))
dry = json.load(open(H / "fake_torino_dry" / "analysis.json"))
runs = [json.loads(line) for line in open(H / "ibm_marrakesh_v1" / "runs.jsonl")]
rows = real["rows"]

cmd("HwRealBackend", real["backend"].replace("_", "\\_"))
cmd("HwRealN", len(rows))
cmd("HwRealRepeats", real["repeats"])
cmd("HwRealShots", runs[0]["shots"])
cmd("HwRealMinQ", min(r["n"] for r in rows))
cmd("HwRealMaxQ", max(r["n"] for r in rows))
for p, tag in (("L3_ours", "LThree"), ("L1_ours", "LOne")):
    cmd(f"HwReal{tag}Ratio", f"{real['summary'][p]['geo_mean_ratio']:.3f}")
    cmd(f"HwReal{tag}Wins", real["summary"][p]["wins"])
cmd("HwDryLThreeRatio", f"{dry['summary']['L3_ours']['geo_mean_ratio']:.3f}")
sds = [v["sd"] for r in rows for v in r["pipes"].values()]
cmd("HwRealSdMin", f"{min(sds):.3f}")
cmd("HwRealSdMax", f"{max(sds):.3f}")
fewer = [r for r in rows if r["pipes"]["L3_ours"]["twoq"] < r["pipes"]["L3"]["twoq"]]
cmd("HwRealTwoqFewerN", len(fewer))
cmd("HwRealAllSaved", f"{100 * (1 - sum(r['pipes']['L3_ours']['total'] for r in rows) / sum(r['pipes']['L3']['total'] for r in rows)):.0f}\\%")
ratios = np.array([r["pipes"]["L3_ours"]["mean"] / r["pipes"]["L3"]["mean"] for r in rows])
cmd("HwRealLThreeMin", f"{ratios.min():.2f}")
cmd("HwRealLThreeMax", f"{ratios.max():.2f}")

with open(EXT / "hw_real_numbers.tex", "w") as fh:
    fh.write("% generated by experiments/make_hardware_assets.py -- do not edit\n")
    for name, val in M.items():
        fh.write(f"\\newcommand{{\\{name}}}{{{val}}}\n")
print(f"wrote {EXT / 'hw_real_numbers.tex'} ({len(M)} macros)")
