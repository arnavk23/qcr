@dataclass
class Config:
    mode: str = "exact"  # "exact" | "phase"
    state_aware: bool = False
    eps: float = 0.0  # per-replacement error budget
    cost: str = "count"  # "count" | "w2" | "calibrated"
    w: int = 16
    max_jump: int = 200
    patience: int = 8
    restarts: int = 1
    log: bool = False  # record a rewrite log for qcr.certify.replay


@dataclass
class Result:
    gates: list
    error_bound: float = 0.0
    stats: dict = field(default_factory=dict)
    seconds: float = 0.0
    log: dict | None = None


class Optimizer:
    def __init__(self, dev: Device, dbs: dict, cfg: Config):
        """dbs: {(kind, topo): Database}, kind in {exact, phase, out, state}."""
        self.dev, self.dbs, self.cfg = dev, dbs, cfg
        self.costf = dev.cost_fn(cfg.cost)
        self.stats = dict(db=0, mitm=0, resynth=0, state=0, out=0, approx=0)
        self.err = 0.0
        self.memo: dict = {}
        self._events = None

    def cost(self, gates):
        return sum(self.costf(g) for g in gates)

    def _topo_map(self, W_phys):
        """Local labelling of the window's wires that fits a database topology."""
        ws = list(W_phys)
        if self.dev.coupling is None or len(ws) < 3:
            return "tri" if self.dev.coupling is None else "line", {q: i for i, q in enumerate(sorted(ws))}
        deg = {q: sum(self.dev.coupled(q, r) for r in ws if r != q) for q in ws}
        mid = max(ws, key=lambda q: deg[q])
        ends = [q for q in ws if q != mid]
        return "line", {ends[0]: 0, mid: 1, ends[1]: 2}

    def _snap_phase(self, scalar, err):
        """Exact mode tracks replacement phases and repairs their product at the end,
        but native gates only reach a discrete set of global phases (multiples of
        pi/4 on Heron, pi/2 on the ion model).  Snap `scalar` to that set: a residual
        is rejected (eps == 0) or charged to the error budget.  Returns (scalar', err')
        or (None, err)."""
        if self.cfg.mode != "exact" or self.cfg.state_aware:
            return scalar, err
        ph = reachable_phases(self.dev)
        near = ph[np.argmin(np.abs(ph - scalar))]
        res = abs(near - scalar)
        if res <= TOL:
            return near, err
        if self.cfg.eps > 0 and err + res <= self.cfg.eps:
            return near, err + res
        return None, err

    def _legal(self, word_phys):
        return all(self.dev.coupled(*g.qubits) for g in word_phys if len(g.qubits) == 2)

    def _best_replacement(self, S_gates, at_start, at_end, longest=True):
        key = (tuple(S_gates), at_start, at_end, longest)
        r = self.memo.get(key)
        if r is None:
            r = self.memo[key] = self._best_replacement_raw(S_gates, at_start, at_end, longest)
        return r

    def _best_replacement_raw(self, S_gates, at_start, at_end, longest):
        Wp = sorted({q for g in S_gates for q in g.qubits})
        topo, m = self._topo_map(Wp)
        inv = {v: q for q, v in m.items()}
        local = [g.remap(m) for g in S_gates]
        U = circuit_unitary(local, K)
        base = self.cost(S_gates)
        best, best_cost, best_err, src = None, base - 1e-9, 0.0, None
        inner = "phase"  # exact mode: phase differences are tracked globally and repaired at the end
        kinds = [inner]
        if self.cfg.state_aware and at_start:
            kinds.append("state")
        if self.cfg.state_aware and at_end and not at_start:
            kinds.append("out")

        best_scalar = 1.0

        def consider(word_local, err, tag):
            nonlocal best, best_cost, best_err, src, best_scalar
            if any(q not in inv for x in word_local for q in x.qubits):
                return
            phys = [x.remap(inv) for x in word_local]
            if not self._legal(phys):
                return
            c = self.cost(phys)
            if c < best_cost:
                sc = 1.0
                if tag not in ("state", "out"):
                    tr = np.trace(U.conj().T @ circuit_unitary(word_local, K)) / D
                    sc, err = self._snap_phase(tr / abs(tr) if abs(tr) > 1e-9 else 1.0, err)
                    if sc is None:
                        return
                best, best_cost, best_err, src, best_scalar = phys, c, err, tag, sc

        if self.cfg.eps > 0:
            e = distance(U, np.eye(D), self.cfg.mode)
            if e <= self.cfg.eps:
                consider([], e, "approx")
        for kind in kinds:
            db = self.dbs.get((kind, topo))
            if db is None:
                continue
            for cand in db.lookup(U, kind):
                consider(cand, 0.0, {"state": "state", "out": "out"}.get(kind, "db"))
            if best is None and longest and len(S_gates) > db.depth and kind == "phase":
                for cand in db.lookup_mitm(U, kind):
                    consider(cand, 0.0, "mitm")
        # analytic resynthesis on <= 2 wires (continuous-angle hardware)
        if len(Wp) <= 2 and len(S_gates) >= 2 and self.dev.continuous_1q:
            m2 = {q: i for i, q in enumerate(Wp)}
            inv2 = {i: q for q, i in m2.items()}
            sub = circuit_unitary([g.remap(m2) for g in S_gates], len(Wp))
            if len(Wp) == 2 and not self.dev.coupled(*Wp):
                cands = []
            elif len(Wp) == 2:
                cands = resynth_2q(sub, self.dev, inner, self.cfg.eps)
            else:
                cands = resynth_1q(sub, self.dev, inner, self.cfg.eps)
            for w, e in cands:
                if w is None:
                    continue
                phys = [x.remap(inv2) for x in w]
                if self._legal(phys) and all(self.dev.is_native(g) for g in phys):
                    c = self.cost(phys)
                    if c < best_cost:
                        tr = np.trace(sub.conj().T @ circuit_unitary(w, len(Wp))) / sub.shape[0]
                        sc, e = self._snap_phase(tr / abs(tr), e)
                        if sc is not None:
                            best, best_cost, best_err, src, best_scalar = phys, c, e, "resynth", sc
        if best is None:
            return 0.0, None
        return base - best_cost, (best, best_err, src, best_scalar)

    def _window(self, g, i, first_idx, occ):
        k = K
        W: set = set()
        jumped: dict = {}
        S = []
        j, misses = i, 0
        while j < len(g) and len(S) < self.cfg.w and misses < self.cfg.max_jump:
            x = g[j]
            new = [q for q in x.qubits if q not in W]
            if len(W) + len(new) <= k and all(commutes_exact(t, x) for q in x.qubits for t in jumped.get(q, ())):
                W |= set(new)
                S.append(j)
            else:
                misses += 1
                for q in x.qubits:
                    jumped.setdefault(q, []).append(x)
            j += 1
        best = (0.0, None, None)
        for L in range(len(S), 0, -1):
            Sl = S[:L]
            Sset = set(Sl)
            Wl = {q for t in Sl for q in g[t].qubits}
            at_start = all(first_idx[q] >= i for q in Wl)
            # output-aware: no other gate at or after position i touches the window's wires
            at_end = self.cfg.state_aware and all(t in Sset for q in Wl for t in occ[q][np.searchsorted(occ[q], i) :])
            if L == 1 and not (self.cfg.state_aware and (at_start or at_end)):
                break
            sav, payload = self._best_replacement([g[t] for t in Sl], at_start, at_end, longest=(L == len(S)))
            if sav > best[0] + 1e-12:
                best = (sav, Sl, payload)
        return best

    def sweep(self, gates):
        g = list(gates)
        C = 1.0 + 0j
        i = 0
        while i < len(g):
            first_idx, occ = {}, {}
            if self.cfg.state_aware:
                for t, x in enumerate(g):
                    for q in x.qubits:
                        first_idx.setdefault(q, t)
                        occ.setdefault(q, []).append(t)
                occ = {q: np.array(v) for q, v in occ.items()}
            else:
                first_idx = {q: -1 for x in g for q in x.qubits}
            sav, S, payload = self._window(g, i, first_idx, occ)
            if sav > 1e-12:
                word, err, src, scalar = payload
                C *= scalar
                if self.cfg.eps > 0 and err > 0:
                    self.err += err
                self.stats[src] += 1
                Sset = set(S)
                if self._events is not None:
                    self._events.append((i, list(S), list(word)))
                rest = [g[t] for t in range(i, S[-1] + 1) if t not in Sset]
                g = g[:i] + word + rest + g[S[-1] + 1 :]
                i = max(0, i - self.cfg.w)
                continue
            i += 1
        return g, C

    def run(self, gates, seed=0) -> Result:

        t0 = time.perf_counter()
        rng = np.random.default_rng(seed)
        best_all, err_all = None, 0.0
        log = self.cfg.log
        for _ in range(self.cfg.restarts):
            self.err = 0.0
            self._events = [] if log else None
            best, C = self.sweep(gates)
            chain = [("sweep", self._events)] if log else None
            fails = 0
            while fails < self.cfg.patience:
                swaps = [] if log else None
                self._events = [] if log else None
                h, c = self.sweep(_shuffle_exact(best, rng, swaps=swaps))
                if self.cost(h) < self.cost(best) - 1e-12:
                    best, C, fails = h, C * c, 0
                    if log:
                        chain += [("shuffle", swaps), ("sweep", self._events)]
                else:
                    fails += 1
            if best_all is None or self.cost(best) < self.cost(best_all):
                best_all, err_all, C_all, chain_all = best, self.err, C, chain
        self._events = None
        stats = dict(self.stats)
        if self.cfg.mode == "exact" and not self.cfg.state_aware:
            best_all, gcost = repair_phase(best_all, C_all, self.dev)
            stats["phase_gadget_gates"] = gcost
        # never worse than the input (the strict phase repair can cost more than it saved)
        stats["kept_input"] = self.cost(best_all) >= self.cost(gates) - 1e-12
        if stats["kept_input"]:
            best_all, err_all = list(gates), 0.0
        cert = dict(chain=chain_all, kept_input=stats["kept_input"]) if log else None
        return Result(best_all, err_all, stats, time.perf_counter() - t0, cert)


def _shuffle_exact(gates, rng, p=0.6, swaps=None):
    g = list(gates)
    done = np.zeros(len(g), bool)
    for i in range(len(g) - 1):
        if not done[i] and rng.random() < p and commutes_exact(g[i], g[i + 1]):
            g[i], g[i + 1] = g[i + 1], g[i]
            done[i + 1] = True
            if swaps is not None:
                swaps.append(i)
    return g


# ---------------------------------------------------------------- global phase repair
_GADGETS: dict = {}


def _gadget_table(dev: Device):
    """Shortest native words on one (or two coupled) qubit(s) equal to c * I."""
    key = dev.name
    if key in _GADGETS:
        return _GADGETS[key]
    table = {}
    for nq in (1, 2):
        if dev.native_2q == "cz":
            one = [Gate("rz", (0,), t) for t in (pi / 2, -pi / 2, pi, -pi, 2 * pi)]
            one += [Gate("sx", (0,)), Gate("x", (0,))]
        else:
            one = [Gate(a, (0,), t) for a in ("rx", "ry", "rz") for t in (pi / 2, -pi / 2, pi, -pi, 2 * pi)]
        pool = list(one)
        if nq == 2:
            pool += [x.remap({0: 1}) for x in one]
            pool += [Gate("cz", (0, 1))] if dev.native_2q == "cz" else [Gate("rxx", (0, 1), t) for t in (pi, -pi)]
        frontier = [([], np.eye(2**nq, dtype=complex))]
        seen = set()
        for _ in range((7 if dev.native_2q == "cz" else 5) if nq == 1 else 3):
            nxt = []
            for w, M in frontier:
                for g in pool:
                    V = gate_matrix(g, nq) @ M
                    k = np.round(V, 6).tobytes()
                    if k in seen:
                        continue
                    seen.add(k)
                    nxt.append((w + [g], V))
                    if np.allclose(V, V[0, 0] * np.eye(2**nq), atol=1e-9, rtol=0):
                        ang = float(np.angle(V[0, 0])) % (2 * pi)  # exact key: matching is to 1e-9
                        ang = next((a for a in table if abs(np.exp(1j * a) - np.exp(1j * ang)) < 1e-9), ang)
                        if ang not in table or len(w) + 1 < len(table[ang][1]):
                            table[ang] = (nq, w + [g])
            frontier = nxt
    _GADGETS[key] = table
    return table


def reachable_phases(dev: Device):
    """Global phases native words can produce (gadget table, closed under the free -1)."""
    key = ("reach", dev.name)
    if key not in _GADGETS:
        a = np.array(list(_gadget_table(dev)))
        _GADGETS[key] = np.unique(np.round(np.exp(1j * np.concatenate([a, a + pi])), 12))
    return _GADGETS[key]


def _absorb_into_rxx(gates, s):
    """Multiply the circuit by s*i (s = +-1) at no 2q cost:
    rxx(t + s pi) rx(pi)_a rx(pi)_b = (-XX)(-s i XX) rxx(t) = s i rxx(t).
    Each rx(pi) is folded into the nearest rx on its wire when one exists (X
    commutes with XX, and with the gates between that do not touch the wire)."""
    k = next((i for i, g in enumerate(gates) if g.name == "rxx"), None)
    if k is None:
        return None
    g = list(gates)
    a, b = g[k].qubits
    g[k] = Gate("rxx", (a, b), g[k].theta + s * pi)
    insert = []
    for q in (a, b):
        nxt = next((j for j in range(k + 1, len(g)) if q in g[j].qubits), None)
        prv = next((j for j in range(k - 1, -1, -1) if q in g[j].qubits), None)
        j = nxt if nxt is not None and g[nxt].name == "rx" else prv if prv is not None and g[prv].name == "rx" else None
        if j is not None:
            g[j] = Gate("rx", (q,), g[j].theta + pi)
        else:
            insert.append(Gate("rx", (q,), pi))
    return g[: k + 1] + insert + g[k + 1 :]


def repair_phase(gates, C, dev: Device):
    """Return (gates', extra_cost) with circuit(gates') = C^{-1} circuit(gates)."""
    # C is a product of snapped phases, but thousands of float multiplications drift
    # past 1e-9 on large circuits; snap it back (same 1e-6 slack as certify's final check)
    ph = reachable_phases(dev)
    near = ph[np.argmin(np.abs(ph - C))]
    if abs(near - C) < 1e-6:
        C = near
    if abs(C - 1) < 1e-9:
        return gates, 0
    need = 1 / C
    if abs(need + 1) < 1e-9:  # -1: shift any rotation by 2 pi (free)
        for i, g in enumerate(gates):
            if g.name in ("rz", "rx", "ry", "rxx", "rzz"):
                g2 = list(gates)
                g2[i] = Gate(g.name, g.qubits, g.theta + 2 * pi)
                return g2, 0
    if abs(abs(need.imag) - 1) < 1e-9:  # +-i: absorb into an existing MS gate (no extra 2q gate)
        g2 = _absorb_into_rxx(gates, 1 if need.imag > 0 else -1)
        if g2 is not None:
            return g2, len(g2) - len(gates)
    table = _gadget_table(dev)

    def find(c):
        return next((v for a, v in table.items() if abs(np.exp(1j * a) - c) < 1e-9), None)

    hit = find(need)
    if hit is None and find(-need) is not None:  # gadget for -need, then a free 2 pi shift
        g2, _ = repair_phase(gates, -1.0, dev)
        gates, hit = g2, find(-need)
    if hit is None:
        raise RuntimeError(f"no phase gadget for {need}")
    nq, w = hit
    q0 = gates[0].qubits[0] if gates else 0
    qs = [q0]
    if nq == 2:
        q1 = next((q for g in gates if len(g.qubits) == 2 and q0 in g.qubits for q in g.qubits if q != q0), None)
        if q1 is None and dev.coupling is None:  # all-to-all: any other wire
            q1 = next((q for g in gates for q in g.qubits if q != q0), q0 + 1)
        if q1 is None:
            raise RuntimeError("no coupled partner for a 2-qubit phase gadget")
        qs.append(q1)
    m = {i: q for i, q in enumerate(qs)}
    return list(gates) + [x.remap(m) for x in w], len(w)
