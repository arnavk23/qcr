"""Gate-set-agnostic, connectivity-aware local optimiser (no Clifford assumption).

Equivalence modes
-----------------
* ``"exact"``: V = U including global phase (safe when the block is later controlled).
* ``"phase"``: V = e^{i phi} U (the paper's notion; kept for comparison).
* ``state_aware``: windows at the start of all their wires only need ``V|0> = U|0>``
  (up to phase); windows before the final measurement of all their wires only
  need V = D U with D diagonal.  Valid when the circuit is a complete program
  (``|0..0>`` input, computational-basis measurement of all qubits).
* ``eps > 0``: a replacement may differ by ``||U - V||_2 <= eps`` (phase-aligned unless
  ``mode == "exact"``); the sum of all such errors is tracked and reported as a bound.

Unifying principle: an equivalence notion is a group action on unitaries (global
phase, left-diagonal, stabiliser of ``|0>``, wire automorphisms of the coupling graph);
the database is keyed by a canonical form of the orbit.

Database
--------
Exhaustive enumeration of <=3-qubit unitaries (or states) generated by a discrete
grid of native gates on a fixed local topology ("tri": all pairs, "line": 0-1-2).
Keys are 64-bit hashes of canonicalised, rounded matrices, minimised over the
topology's automorphisms.  Levels < depth keep matrices; the deepest level keeps
keys only.  Every hit is verified numerically before use.  Meet-in-the-middle
(U = R A, A in a full ball of radius 2) extends the reach by two gates.

Fallback for circuits unlike the database
-----------------------------------------
Windows on <=2 coupled wires are resynthesised exactly (or within eps): IBM-style
fixed-CZ devices by KAK into rz/sx/x/cz with the minimal number of CZ; ion devices
by a Weyl decomposition into arbitrary-angle MS gates (one per non-zero
interaction coefficient); single-qubit runs by Euler decomposition.
"""

from __future__ import annotations

import time
from dataclasses import dataclass, field
from itertools import permutations
from math import pi

import numpy as np

from .gates import Gate, circuit_unitary, gate_matrix
from .hardware import Device

K = 3
D = 2**K
TOPO_PAIRS = {"tri": [(0, 1), (0, 2), (1, 2)], "line": [(0, 1), (1, 2)]}
TOPO_AUTOS = {"tri": list(permutations(range(K))), "line": [(0, 1, 2), (2, 1, 0)]}
_rng = np.random.default_rng(12345)
SCALE = 1e6
TOL = 1e-10  # "exact": numerically exact (8x8 products are accurate to ~1e-14)


def _hash_coeffs(m):
    return (np.random.default_rng(777 + m).integers(1, 2**62, size=m, dtype=np.int64) * 2 + 1).astype(np.uint64)


HC_MAT = _hash_coeffs(2 * D * D)
HC_VEC = _hash_coeffs(2 * D)


# ---------------------------------------------------------------- exact commutation
_comm: dict = {}


def commutes_exact(a: Gate, b: Gate) -> bool:
    if not set(a.qubits) & set(b.qubits):
        return True
    key = (a, b)
    r = _comm.get(key)
    if r is None:
        W = sorted(set(a.qubits) | set(b.qubits))
        m = {q: i for i, q in enumerate(W)}
        A, B = a.remap(m), b.remap(m)
        k = len(W)
        r = bool(np.allclose(circuit_unitary([A, B], k), circuit_unitary([B, A], k), atol=1e-10, rtol=0))
        _comm[key] = r
    return r


# ---------------------------------------------------------------- canonical keys
def _permute(M, perm):
    N = M.shape[0]
    if M.ndim == 2:  # states
        return M.reshape(N, 2, 2, 2).transpose([0] + [1 + p for p in perm]).reshape(N, D)
    t = M.reshape(N, 2, 2, 2, 2, 2, 2)
    return t.transpose([0] + [1 + p for p in perm] + [4 + p for p in perm]).reshape(N, D, D)


def _phase_fix(flat):
    N = flat.shape[0]
    idx = np.argmax(np.abs(flat) > 1e-6, axis=1)
    piv = flat[np.arange(N), idx]
    return flat * (np.abs(piv) / piv)[:, None]


def _normalise(M, kind):
    N = M.shape[0]
    if kind == "state":
        return _phase_fix(M.reshape(N, D))
    if kind == "exact":
        return M.reshape(N, -1)
    if kind == "phase":
        return _phase_fix(M.reshape(N, -1))
    if kind == "out":  # left-multiplication by a diagonal: fix each row's phase
        R = M.reshape(N * D, D)
        return _phase_fix(R).reshape(N, -1)
    raise ValueError(kind)


def _hash(flat):
    q = np.rint(np.concatenate([flat.real, flat.imag], axis=1) * SCALE).astype(np.int64).view(np.uint64)
    hc = HC_VEC if flat.shape[1] == D else HC_MAT
    return (q * hc).sum(axis=1, dtype=np.uint64)


def canonical_keys(M, kind, topo):
    ks = np.stack([_hash(_normalise(_permute(M, p), kind)) for p in TOPO_AUTOS[topo]])
    return ks.min(axis=0)


def equivalent_local(U, V, kind, tol=TOL):
    """Is V an acceptable replacement for U under `kind` (8x8 / length-8)?
    Tests are linear in the operator error: fidelity-style tests such as
    ``|tr(U^dag V)|/D ~ 1`` are quadratic and would accept errors of order sqrt(tol)."""
    if kind == "state":
        u, v = U[:, 0], V[:, 0]
        o = np.vdot(u, v)
        return abs(o) > 1e-12 and np.linalg.norm(u * (o / abs(o)) - v) < tol
    if kind == "exact":
        return np.linalg.norm(U - V, 2) < tol
    if kind == "phase":
        return distance(U, V, "phase") < tol
    if kind == "out":
        P = V @ U.conj().T
        return np.abs(P - np.diag(np.diag(P))).max() < tol and np.allclose(np.abs(np.diag(P)), 1, atol=tol, rtol=0)
    raise ValueError(kind)


def distance(U, V, kind):
    """Operator distance used for approximate replacements."""
    if kind == "exact":
        return float(np.linalg.norm(U - V, 2))
    tr = np.trace(U.conj().T @ V)
    ph = tr / abs(tr) if abs(tr) > 1e-12 else 1.0
    return float(np.linalg.norm(U * ph - V, 2))


# ---------------------------------------------------------------- database
@dataclass
class GridAlphabet:
    """Discrete native-gate grid used to enumerate the database."""

    one_q: dict  # gate name -> tuple of angles (None for fixed gates like sx)
    two_q: str
    two_q_angles: tuple = (None,)

    def pool(self, topo):
        p = []
        for name, angles in self.one_q.items():
            for q in range(K):
                for t in angles:
                    p.append(Gate(name, (q,), 0.0 if t is None else t))
        for a, b in TOPO_PAIRS[topo]:
            for t in self.two_q_angles:
                p.append(Gate(self.two_q, (a, b), 0.0 if t is None else t))
        return p


GRID8 = (-pi / 4, pi / 4, -pi / 2, pi / 2, pi)
HALF = (-pi / 2, pi / 2)
GRIDS = {
    "ion_paper": GridAlphabet({"rx": HALF, "ry": HALF, "rz": HALF}, "rxx", HALF),
    "ibm_paper": GridAlphabet({"rx": HALF, "rz": HALF}, "cz"),
    "heron": GridAlphabet({"rz": GRID8, "sx": (None,), "x": (None,)}, "cz"),
    "ion": GridAlphabet({"rx": GRID8, "ry": GRID8, "rz": GRID8}, "rxx", (pi / 4, -pi / 4, pi / 2, -pi / 2)),
}


class Database:
    def __init__(
        self, grid: GridAlphabet, topo: str, kind: str, depth: int, chunk=50_000, verbose=True, max_frontier=2_500_000
    ):
        t0 = time.time()
        self.kind, self.topo, self.depth = kind, topo, depth
        # classes {D U} are preserved by right multiplication only: grow the
        # output-aware database by prepending gates (earlier in time)
        self.right = kind == "out"
        self.pool = grid.pool(topo)
        G = np.stack([gate_matrix(g, K) for g in self.pool])
        state = kind == "state"
        start = np.eye(D, dtype=complex)[None]
        if state:
            start = start[:, :, :1]  # |000> as a column
        keyf = (
            (lambda M: canonical_keys(M[:, :, 0], "state", topo))
            if state
            else (lambda M: canonical_keys(M, kind, topo))
        )
        k0 = keyf(start)
        keys, parent, op, dist = [k0], [np.array([-1])], [np.array([-1])], [np.array([0])]
        known = np.sort(k0)
        frontier, fids, n_total = start, np.array([0]), 1
        self.levels = [1]
        for d in range(1, depth + 1):
            last = d == depth or len(frontier) * len(G) > 40 * max_frontier
            lk, lp, lo, lm = [], [], [], []
            for s in range(0, len(frontier), chunk):
                F, ids = frontier[s : s + chunk], fids[s : s + chunk]
                for o, g in enumerate(G):
                    C = np.einsum("nij,jk->nik", F, g) if self.right else np.einsum("ij,njk->nik", g, F)
                    k = keyf(C)
                    p = np.searchsorted(known, k)
                    p[p >= len(known)] = 0
                    new = known[p] != k
                    if new.any():
                        lk.append(k[new]), lp.append(ids[new]), lo.append(np.full(new.sum(), o))
                        if not last:
                            lm.append(C[new])
            if not lk:
                break
            k = np.concatenate(lk)
            uk, first = np.unique(k, return_index=True)
            keys.append(uk), parent.append(np.concatenate(lp)[first]), op.append(np.concatenate(lo)[first])
            dist.append(np.full(len(uk), d))
            known = np.sort(np.concatenate([known, uk]))
            fids = np.arange(n_total, n_total + len(uk))
            n_total += len(uk)
            self.levels.append(len(uk))
            if verbose:
                print(
                    f"  DB[{kind},{topo}] depth {d}: +{len(uk):,} (total {n_total:,}) {time.time() - t0:.0f}s",
                    flush=True,
                )
            if last:
                self.depth = d
                break
            frontier = np.concatenate(lm)[first]
        self.keys_by_id = np.concatenate(keys)
        self.parent = np.concatenate(parent).astype(np.int64)
        self.op = np.concatenate(op).astype(np.int32)
        self.dist = np.concatenate(dist).astype(np.uint8)
        order = np.argsort(self.keys_by_id, kind="stable")
        self.sorted_keys, self.sorted_ids = self.keys_by_id[order], order
        self.build_seconds = time.time() - t0
        self.keyf = keyf
        self.mitm = None if state else self._ball(2 if len(self.pool) <= 30 else 1)

    @property
    def size(self):
        return len(self.keys_by_id)

    def save(self, path):
        np.savez(
            path,
            keys_by_id=self.keys_by_id,
            parent=self.parent,
            op=self.op,
            dist=self.dist,
            levels=np.array(self.levels),
            meta=np.array([self.kind, self.topo, str(self.depth)]),
            build_seconds=np.array([self.build_seconds]),
        )

    @classmethod
    def load(cls, path, grid: GridAlphabet):
        z = np.load(path)
        self = cls.__new__(cls)
        self.kind, self.topo, depth = [str(x) for x in z["meta"]]
        self.depth = int(depth)
        self.right = self.kind == "out"
        self.pool = grid.pool(self.topo)
        self.keys_by_id, self.parent, self.op, self.dist = z["keys_by_id"], z["parent"], z["op"], z["dist"]
        self.levels = z["levels"].tolist()
        self.build_seconds = float(z["build_seconds"][0])
        order = np.argsort(self.keys_by_id, kind="stable")
        self.sorted_keys, self.sorted_ids = self.keys_by_id[order], order
        state = self.kind == "state"
        topo, kind = self.topo, self.kind
        self.keyf = (
            (lambda M: canonical_keys(M[:, :, 0], "state", topo))
            if state
            else (lambda M: canonical_keys(M, kind, topo))
        )
        self.mitm = None if state else self._ball(2 if len(self.pool) <= 30 else 1)
        return self

    def _ball(self, m):
        words, mats = [[]], [np.eye(D, dtype=complex)]
        seen = {_hash(_normalise(mats[0][None], self.kind if self.kind != "state" else "phase"))[0]}
        frontier = [([], mats[0])]
        for _ in range(m):
            nxt = []
            for w, U in frontier:
                for o, g in enumerate(self.pool):
                    V = gate_matrix(g, K) @ U
                    k = _hash(_normalise(V[None], "exact"))[0]
                    if k not in seen:
                        seen.add(k)
                        nxt.append((w + [o], V))
            words += [w for w, _ in nxt]
            mats += [V for _, V in nxt]
            frontier = nxt
        return words, np.stack([M.conj().T for M in mats])

    def word(self, i):
        w = []
        while self.parent[i] >= 0:
            w.append(int(self.op[i]))
            i = int(self.parent[i])
        if not self.right:
            w = w[::-1]
        return [self.pool[o] for o in w]

    def _candidates(self, U, ids, kind):
        out = []
        for i in ids:
            w = self.word(int(i))
            for p in TOPO_AUTOS[self.topo]:
                cand = [x.remap(dict(enumerate(p))) for x in w]
                if equivalent_local(U, circuit_unitary(cand, K), kind):
                    out.append(cand)
                    break
        return out

    def lookup(self, U, kind):
        k = self.keyf(U[None] if kind != "state" else U[None, :, :1])[0]
        lo, hi = np.searchsorted(self.sorted_keys, k, "left"), np.searchsorted(self.sorted_keys, k, "right")
        return self._candidates(U, self.sorted_ids[lo:hi], kind) if hi > lo else []

    def lookup_mitm(self, U, kind):
        if self.mitm is None:
            return []
        words, inv = self.mitm
        R = np.einsum("ij,njk->nik", U, inv)
        k = self.keyf(R)
        p = np.searchsorted(self.sorted_keys, k)
        p[p >= len(self.sorted_keys)] = 0
        out = []
        for h in np.flatnonzero(self.sorted_keys[p] == k)[:64]:
            for wr in self._candidates(R[h], [self.sorted_ids[p[h]]], kind):
                cand = [self.pool[o] for o in words[h]] + wr
                if equivalent_local(U, circuit_unitary(cand, K), kind):
                    out.append(cand)
        return out


# ---------------------------------------------------------------- resynthesis
def _q2ours(qc, n):
    """qiskit circuit (little-endian) -> our gates (qubit 0 = most significant)."""
    out = []
    for inst in qc.data:
        nm = inst.operation.name
        qs = tuple(n - 1 - qc.find_bit(q).index for q in inst.qubits)
        prm = [float(x) for x in inst.operation.params]
        if nm in ("rx", "ry", "rz", "rxx", "rzz"):
            if abs(((prm[0] + 2 * pi) % (4 * pi)) - 2 * pi) < 1e-12:  # 4pi-periodic identity
                continue
            out.append(Gate(nm, tuple(sorted(qs)) if len(qs) == 2 else qs, prm[0]))
        elif nm in ("sx", "x"):
            out.append(Gate(nm, qs))
        elif nm == "cz":
            out.append(Gate("cz", tuple(sorted(qs))))
        elif nm in ("global_phase", "barrier", "id", "delay"):
            continue
        else:
            raise ValueError(nm)
    return out


def _fix_phase(word, U, n, kind, eps):
    """Make `word` equal U exactly (kind 'exact') using rz/rx(theta+2pi) = -rz/rx(theta).
    Returns (word, error) or (None, inf)."""
    V = circuit_unitary(word, n)
    if kind != "exact":
        e = distance(U, V, "phase")
        return (word, e) if e <= max(eps, TOL) else (None, np.inf)
    e = distance(U, V, "exact")
    if e <= max(eps, TOL):
        return word, e
    if np.linalg.norm(U + V, 2) <= max(eps, TOL):  # off by -1
        for i, g in enumerate(word):
            if g.name in ("rz", "rx", "ry", "rxx", "rzz"):
                w2 = list(word)
                w2[i] = Gate(g.name, g.qubits, g.theta + 2 * pi)
                return w2, float(np.linalg.norm(U - circuit_unitary(w2, n), 2))
    return None, np.inf


def resynth_1q(U2, dev: Device, kind, eps):
    from qiskit.synthesis import OneQubitEulerDecomposer

    basis = "ZSXX" if dev.native_2q == "cz" else "ZYZ"
    w = _q2ours(OneQubitEulerDecomposer(basis)(U2), 1)
    return [_fix_phase(w, U2, 1, kind, eps)]


def _ms_weyl(U4, a, b, c, K1l, K1r, K2l, K2r):
    """U = phase (K1l x K1r) exp(i(aXX+bYY+cZZ)) (K2l x K2r) with arbitrary-angle MS."""
    from qiskit.synthesis import OneQubitEulerDecomposer

    e = OneQubitEulerDecomposer("ZYZ")

    def loc(M, q):
        return [Gate(g.name, (q,), g.theta) for g in _q2ours(e(M), 1)]

    w = loc(K2l, 0) + loc(K2r, 1)
    if abs(a) > 1e-10:
        w.append(Gate("rxx", (0, 1), -2 * a))
    if abs(b) > 1e-10:  # YY = Rz(pi/2)xRz(pi/2) XX (..)^dag
        w += [
            Gate("rz", (0,), -pi / 2),
            Gate("rz", (1,), -pi / 2),
            Gate("rxx", (0, 1), -2 * b),
            Gate("rz", (0,), pi / 2),
            Gate("rz", (1,), pi / 2),
        ]
    if abs(c) > 1e-10:  # ZZ = Ry(-pi/2)xRy(-pi/2) XX (..)^dag
        w += [
            Gate("ry", (0,), pi / 2),
            Gate("ry", (1,), pi / 2),
            Gate("rxx", (0, 1), -2 * c),
            Gate("ry", (0,), -pi / 2),
            Gate("ry", (1,), -pi / 2),
        ]
    w += loc(K1l, 0) + loc(K1r, 1)
    return w


def resynth_2q(U4, dev: Device, kind, eps):
    """List of (word, error) candidates on local wires 0,1."""
    out = []
    if dev.native_2q == "cz":
        from qiskit.circuit.library import CZGate
        from qiskit.synthesis import TwoQubitBasisDecomposer

        dec = TwoQubitBasisDecomposer(CZGate(), euler_basis="ZSXX")
        for k in range(4):
            w = _q2ours(dec(U4, _num_basis_uses=k), 2)
            wf, e = _fix_phase(w, U4, 2, kind, eps)
            if wf is not None:
                out.append((wf, e))
                break
    else:
        from qiskit.synthesis.two_qubit.two_qubit_decompose import TwoQubitWeylDecomposition

        wd = TwoQubitWeylDecomposition(U4)
        # TwoQubitWeylDecomposition is little-endian: K1l acts on qiskit qubit 1 = our qubit 0
        w = _ms_weyl(U4, wd.a, wd.b, wd.c, wd.K1l, wd.K1r, wd.K2l, wd.K2r)
        cands = [w]
        if eps > 0:  # approximate: drop the smallest interaction terms
            for drop in ("c", "bc"):
                a, b, c = wd.a, wd.b, wd.c
                if "b" in drop:
                    b = 0.0
                if "c" in drop:
                    c = 0.0
                cands.append(_ms_weyl(U4, a, b, c, wd.K1l, wd.K1r, wd.K2l, wd.K2r))
        for w in cands:
            wf, e = _fix_phase(w, U4, 2, kind, eps)
            if wf is not None:
                out.append((wf, e))
    return out


