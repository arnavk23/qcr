"""Exact, bit-packed Clifford tableaux (used by the extension experiments).

Every gate in the paper's pools (rotations by +-pi/2, rxx(+-pi/2), cz) is
a Clifford gate, so every circuit is an element of the finite Clifford
group C_n / U(1).  A Clifford U modulo global phase is uniquely determined
by its signed tableau: the images U P U^dag of P in {X_1..X_n, Z_1..Z_n}.

Encoding (n <= 3 so that everything fits in one uint64)::

  a signed Pauli string = 2n bits (x|z per qubit) + 1 sign bit  -> R = 2n+1 bits
  an element            = 2n such rows                          -> 2n*R bits

Left-multiplying by a gate G acts on each row independently through a
lookup table T_G[row] (computed once numerically), so a whole BFS level is
a few vectorised numpy gathers.
"""

from __future__ import annotations

import time

import numpy as np

from .gates import Gate, gate_matrix

PAULI = {
    (0, 0): np.eye(2, dtype=complex),
    (1, 0): np.array([[0, 1], [1, 0]], dtype=complex),
    (1, 1): np.array([[0, -1j], [1j, 0]], dtype=complex),  # Y (Hermitian)
    (0, 1): np.array([[1, 0], [0, -1]], dtype=complex),
}


def pauli_matrix(bits: int, n: int) -> np.ndarray:
    """bits: x_0..x_{n-1} z_0..z_{n-1} packed as (x_q << q) | (z_q << (n+q))."""
    M = np.eye(1, dtype=complex)
    for q in range(n):
        M = np.kron(M, PAULI[((bits >> q) & 1, (bits >> (n + q)) & 1)])
    return M


class Tableau:
    def __init__(self, n: int):
        assert n <= 3, "single-uint64 packing supports n <= 3"
        self.n = n
        self.R = 2 * n + 1
        self.rows = 2 * n
        self.mask = (1 << self.R) - 1
        self.P = [pauli_matrix(b, n) for b in range(4**n)]

    def row_table(self, U: np.ndarray) -> np.ndarray:
        """T[signed row] -> signed row of U (row) U^dag."""
        n = self.n
        T = np.zeros(1 << self.R, dtype=np.uint64)
        Ud = U.conj().T
        for b in range(4**n):
            Q = U @ self.P[b] @ Ud
            for c in range(4**n):
                ov = np.vdot(self.P[c], Q) / 2**n
                if abs(abs(ov) - 1) < 1e-8:
                    s = 0 if ov.real > 0 else 1
                    T[b] = c | (s << (2 * n))
                    T[b | (1 << (2 * n))] = c | ((1 - s) << (2 * n))
                    break
            else:
                raise ValueError("gate is not Clifford")
        return T

    def identity_code(self) -> int:
        n = self.n
        code = 0
        for q in range(n):
            code |= (1 << q) << (self.R * q)  # X_q
            code |= (1 << (n + q)) << (self.R * (n + q))  # Z_q
        return code

    def apply(self, T: np.ndarray, codes: np.ndarray) -> np.ndarray:
        out = np.zeros_like(codes)
        m = np.uint64(self.mask)
        for r in range(self.rows):
            sh = np.uint64(self.R * r)
            out |= T[(codes >> sh) & m] << sh
        return out

    def code_of(self, gates, tables) -> int:
        c = np.array([self.identity_code()], dtype=np.uint64)
        for g in gates:
            c = self.apply(tables[g], c)
        return int(c[0])


def cayley_bfs(n: int, pool: list[Gate], chunk=4_000_000, verbose=True, max_depth=99):
    """Breadth-first enumeration of the whole group generated by `pool`.

    Returns (sorted codes, distance per code, level sizes, tableau, tables)."""
    tb = Tableau(n)
    tables = {g: tb.row_table(gate_matrix(g, n)) for g in pool}
    Ts = list(tables.values())
    ident = np.array([tb.identity_code()], dtype=np.uint64)
    visited = ident.copy()
    dists = np.zeros(1, dtype=np.uint8)
    frontier = ident
    levels = [1]
    t0 = time.time()
    d = 0
    while len(frontier) and d < max_depth:
        d += 1
        new_parts = []
        for s in range(0, len(frontier), chunk):
            f = frontier[s : s + chunk]
            cand = np.unique(np.concatenate([tb.apply(T, f) for T in Ts]))
            pos = np.searchsorted(visited, cand)
            pos[pos >= len(visited)] = 0
            cand = cand[visited[pos] != cand]
            new_parts.append(cand)
        new = np.unique(np.concatenate(new_parts)) if new_parts else np.zeros(0, np.uint64)
        if len(new) == 0:
            break
        allc = np.concatenate([visited, new])
        alld = np.concatenate([dists, np.full(len(new), d, np.uint8)])
        o = np.argsort(allc, kind="stable")
        visited, dists = allc[o], alld[o]
        frontier = new
        levels.append(len(new))
        if verbose:
            print(f"  n={n} depth {d}: +{len(new):,} (total {len(visited):,}) {time.time() - t0:.0f}s", flush=True)
    return visited, dists, levels, tb, tables


class ExactOracle:
    """Optimal gate count of any n<=3 circuit over `pool` via a full BFS table."""

    def __init__(self, n, pool, codes, dists, tb, tables):
        self.n, self.pool, self.codes, self.dists, self.tb, self.tables = n, pool, codes, dists, tb, tables

    def distance_of_codes(self, c: np.ndarray) -> np.ndarray:
        pos = np.searchsorted(self.codes, c)
        assert np.all(self.codes[pos] == c)
        return self.dists[pos]

    def distance(self, gates) -> int:
        return int(self.distance_of_codes(np.array([self.tb.code_of(gates, self.tables)], np.uint64))[0])

    def optimal_word(self, gates) -> list[Gate]:
        """Greedy descent: peel a last gate g with d(g^-1 U) = d(U) - 1."""
        code = np.array([self.tb.code_of(gates, self.tables)], np.uint64)
        d = int(self.distance_of_codes(code)[0])
        inv = {}
        for g in self.pool:  # inverse of g as a table: g^{-1} = g^3 for pi/2 rotations
            T = self.tables[g]
            inv[g] = T[T[T]]
        word = []
        while d > 0:
            for g in self.pool:
                prev = self.tb.apply(inv[g], code)
                if int(self.distance_of_codes(prev)[0]) == d - 1:
                    word.append(g)
                    code, d = prev, d - 1
                    break
        return word[::-1]


class WideTableau:
    """Tableau encoding for any n: rows packed into W uint64 words, elements
    stored as (N, W) arrays and compared via a 8W-byte void view."""

    def __init__(self, n: int):
        self.n = n
        self.R = 2 * n + 1
        self.rows = 2 * n
        self.rpw = 64 // self.R
        self.W = -(-self.rows // self.rpw)
        self.mask = (1 << self.R) - 1
        self._small = Tableau.__new__(Tableau)
        self._small.n, self._small.R, self._small.rows, self._small.mask = n, self.R, self.rows, self.mask
        self._small.P = [pauli_matrix(b, n) for b in range(4**n)]

    def row_table(self, U):
        return Tableau.row_table(self._small, U)

    def pos(self, r):
        return r // self.rpw, np.uint64(self.R * (r % self.rpw))

    def identity(self):
        c = np.zeros((1, self.W), dtype=np.uint64)
        n = self.n
        for q in range(n):
            for r, bits in ((q, 1 << q), (n + q, 1 << (n + q))):
                w, sh = self.pos(r)
                c[0, w] |= np.uint64(bits) << sh
        return c

    def apply(self, T, codes):
        out = np.zeros_like(codes)
        m = np.uint64(self.mask)
        for r in range(self.rows):
            w, sh = self.pos(r)
            out[:, w] |= T[(codes[:, w] >> sh) & m] << sh
        return out

    def key(self, codes):
        return np.ascontiguousarray(codes).view(np.dtype((np.void, 8 * self.W))).ravel()


def wide_ball_sizes(n, pool, max_depth, chunk=2_000_000, verbose=True):
    """Exact sphere sizes ``|S(d)|``, d <= max_depth, for any n (memory permitting)."""
    from .gates import gate_matrix

    tb = WideTableau(n)
    Ts = [tb.row_table(gate_matrix(g, n)) for g in pool]
    frontier = tb.identity()
    ball = np.sort(tb.key(frontier))
    sizes = [1]
    t0 = time.time()
    for d in range(1, max_depth + 1):
        parts = []
        for s in range(0, len(frontier), chunk):
            f = frontier[s : s + chunk]
            nb = np.concatenate([tb.apply(T, f) for T in Ts])
            k = tb.key(nb)
            _, idx = np.unique(k, return_index=True)
            nb = nb[idx]
            k = tb.key(nb)
            p = np.searchsorted(ball, k)
            p[p >= len(ball)] = 0
            parts.append(nb[ball[p] != k])
        nb = np.concatenate(parts)
        k = tb.key(nb)
        _, idx = np.unique(k, return_index=True)
        frontier = nb[idx]
        ball = np.sort(np.concatenate([ball, tb.key(frontier)]))
        sizes.append(len(frontier))
        if verbose:
            print(f"  n={n} depth {d}: |S|={len(frontier):,} {time.time() - t0:.0f}s", flush=True)
    return sizes


def twoq_bfs(n: int, pool: list[Gate], chunk=4_000_000, verbose=True):
    """0-1 BFS: minimal number of two-qubit gates for every group element
    (single-qubit gates are free).  Returns (sorted codes, c2 per code, layer sizes)."""
    tb = Tableau(n)
    one = [tb.row_table(gate_matrix(g, n)) for g in pool if len(g.qubits) == 1]
    two = [tb.row_table(gate_matrix(g, n)) for g in pool if len(g.qubits) == 2]
    visited = np.zeros(0, np.uint64)

    def novel(c):
        c = np.unique(c)
        if len(visited):
            p = np.searchsorted(visited, c)
            p[p >= len(visited)] = 0
            c = c[visited[p] != c]
        return c

    layers, c2parts = [], []
    seed = np.array([tb.identity_code()], dtype=np.uint64)
    k = 0
    t0 = time.time()
    while len(seed):
        layer = [seed]
        visited = np.sort(np.concatenate([visited, seed]))
        frontier = seed
        while len(frontier):  # closure under free single-qubit gates
            parts = [
                novel(np.concatenate([tb.apply(T, frontier[s : s + chunk]) for T in one]))
                for s in range(0, len(frontier), chunk)
            ]
            frontier = novel(np.concatenate(parts)) if parts else np.zeros(0, np.uint64)
            if len(frontier):
                visited = np.sort(np.concatenate([visited, frontier]))
                layer.append(frontier)
        layer = np.concatenate(layer)
        layers.append(len(layer))
        c2parts.append((layer, k))
        if verbose:
            print(
                f"  2q-count {k}: {len(layer):,} elements (total {len(visited):,}) {time.time() - t0:.0f}s", flush=True
            )
        parts = [
            novel(np.concatenate([tb.apply(T, layer[s : s + chunk]) for T in two])) for s in range(0, len(layer), chunk)
        ]
        seed = novel(np.concatenate(parts)) if parts else np.zeros(0, np.uint64)
        k += 1
    codes = np.concatenate([c for c, _ in c2parts])
    c2 = np.concatenate([np.full(len(c), kk, np.uint8) for c, kk in c2parts])
    o = np.argsort(codes)
    return codes[o], c2[o], layers
